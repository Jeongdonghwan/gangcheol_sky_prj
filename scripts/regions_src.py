def build():
    out = {}
    for label, unit, parent, city, full, note, spots, jobs in MAJOR:
        out[label] = dict(label=label, name=full.split(' (')[0].split(' ')[-1], unit=unit, parent=parent, city=city,
                          full=full, note=note, spots=spots, jobs=jobs, gu=label)
    for label, (parent, note) in AREA.items():
        P = out[parent]
        out[label] = dict(label=label, name=label.replace('김포 ', ''), unit='생활권', parent=parent, city=P['city'],
                          full=f"{P['full'].split(' (')[0]} {label.replace('김포 ', '')}", note=note, spots=[], jobs=P['jobs'], gu=parent)
    for label, (parent, note) in DONG.items():
        P = out[parent]
        name = next((label[len(x):] for x in PREFIX if label.startswith(x)), label)
        out[label] = dict(label=label, name=name, unit='동·읍면', parent=parent, city=P['city'],
                          full=f"{P['full'].split(' (')[0]} {name}", note=note, spots=[], jobs=P['jobs'], gu=parent)
    return out


